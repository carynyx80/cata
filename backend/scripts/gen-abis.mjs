// Generates src/abis/*.ts from forge build output (contracts/out). Usage: npm run gen:abis
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join, dirname } from "node:path";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const out = join(root, "..", "contracts", "out");
const CONTRACTS = ["CataConfig", "CataPoints", "CataPriceIndex", "CataVault", "PackMachine"];

for (const name of CONTRACTS) {
  const f = join(out, `${name}.sol`, `${name}.json`);
  if (!existsSync(f)) { console.error(`missing ${f} — run forge build in contracts/`); process.exit(1); }
  const { abi } = JSON.parse(readFileSync(f, "utf8"));
  const src = `// AUTO-GENERATED by scripts/gen-abis.mjs from contracts/out/${name}.sol/${name}.json — do not edit.\nexport const ${name[0].toLowerCase() + name.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(join(root, "src", "abis", `${name}.ts`), src);
  console.log(`wrote src/abis/${name}.ts (${abi.length} entries)`);
}
