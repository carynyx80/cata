// Generates web/lib/abis/*.ts (as const) from the forge build output in ../contracts/out.
// Usage: node scripts/gen-abis.mjs   (run `forge build` in ../contracts first if out/ is stale)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "../../contracts/out");
const dest = join(here, "../lib/abis");
const names = [
  "CataConfig", "PackMachine", "CataVault", "CataMarket", "GiftPacks", "CataPoints", "SetRewards",
  "CataPriceIndex", "PredictionMarket", "CardLending", "LiveRips", "PackBattles", "FractionalGrails", "CataTreasury",
];

if (!existsSync(outDir)) {
  console.error(`missing ${outDir}: run \`forge build\` in contracts/ first`);
  process.exit(1);
}
mkdirSync(dest, { recursive: true });
const index = [];
for (const n of names) {
  const file = join(outDir, `${n}.sol`, `${n}.json`);
  const { abi } = JSON.parse(readFileSync(file, "utf8"));
  const id = n[0].toLowerCase() + n.slice(1) + "Abi";
  writeFileSync(join(dest, `${n}.ts`), `// generated by scripts/gen-abis.mjs from contracts/out — do not edit\nexport const ${id} = ${JSON.stringify(abi, null, 2)} as const;\n`);
  index.push(`export { ${id} } from "./${n}";`);
  console.log(`${n}: ${abi.length} entries`);
}
writeFileSync(join(dest, "index.ts"), `// generated by scripts/gen-abis.mjs — do not edit\n${index.join("\n")}\n`);
